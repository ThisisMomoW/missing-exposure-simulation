source(file.path(root,"R/workflow.R"))
opt <- parse_options(list(run="bundled",incomplete="error"))
if(!opt$incomplete %in% c("error","allow")) stop("incomplete must be error or allow")
x <- read_run(opt$run)
if(length(x$missing) && opt$incomplete=="error") stop(length(x$missing)," attempted records are missing")
s <- operating_characteristics(x$records)
folder <- file.path(root,"outputs/summaries",opt$run)
dir.create(folder,recursive=TRUE,showWarnings=FALSE)
atomic_rds(x,file.path(folder,"replications.rds"))
atomic_rds(s,file.path(folder,"summary.rds"))
utils::write.csv(s,file.path(folder,"summary.csv"),row.names=FALSE)
utils::write.csv(data.frame(key=x$missing),file.path(folder,"missing.csv"),row.names=FALSE)
message(nrow(x$records)," attempts; ",sum(x$records$valid)," valid; ",length(x$missing)," absent")
